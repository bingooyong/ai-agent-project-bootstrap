const TemplateVersion = "1.0.0"
const AdapterVersion = adapters.CodexVersion

// TemplateFingerprint hashes the deterministic parsed template representation.
func TemplateFingerprint() string { return safeio.Digest([]byte(document.Tree.Root.String())) }

type File struct {
	Path    string `json:"path"`
	Content string `json:"content"`
}

type module struct {
	path      string
	manifests []string
	languages []string
}

type commandView struct{ Name, Invocation, Cwd, Status, Sources string }
type ruleView struct{ ID, Title, Version, Severity, Source, Scope, Conditions, Applicability, SHA256, Content string }
type view struct {
	Root            bool
	Module          string
	Manifests       string
	Languages       string
	TemplateVersion string
	AdapterVersion  string
	Fingerprint     string
	Commands        []commandView
	Rules           []ruleView
	Children        []string
	Unknown         []string
	Warnings        []string
}

