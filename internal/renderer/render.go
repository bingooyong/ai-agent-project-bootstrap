// Render emits root and explicit module instructions with deterministic bytes.
// It performs no file access, command execution, source loading or template
// evaluation of rule bodies. The caller owns existing-file/override checks.
func Render(profile model.Profile, resolved rules.Resolution) ([]File, error) {
	if profile.SchemaVersion != "1.0" || profile.Coverage.Status != "complete" {
		return nil, errors.New("render requires a complete supported project profile")
	}
	if !hexDigest(resolved.Fingerprint) {
		return nil, errors.New("render requires a resolved rule fingerprint")
	}
	modules, err := aggregate(profile.Modules)
	if err != nil {
		return nil, err
	}
	paths := make([]string, 0, len(modules))
	for name := range modules {
		paths = append(paths, name)
	}
	sort.Strings(paths)
	selected := map[string]map[string]bool{}
	for _, c := range profile.Commands {
		if _, err := renderCommand(c); err != nil {
			return nil, err
		}
	}
	var files []File
	for _, name := range paths {
		m := modules[name]
		v := view{Root: name == ".", Module: inline(name), Manifests: inlineList(m.manifests), Languages: inlineList(m.languages), TemplateVersion: TemplateVersion, AdapterVersion: AdapterVersion, Fingerprint: inline(resolved.Fingerprint)}
		for _, c := range profile.Commands {
			if owner(path.Join(c.Cwd, "_command"), modules) != name {
				continue
			}
			cv, err := renderCommand(c)
			if err != nil {
				return nil, err
			}
			v.Commands = append(v.Commands, cv)
		}
		sort.Slice(v.Commands, func(i, j int) bool {
			a, b := v.Commands[i], v.Commands[j]
			return a.Name+"\x00"+a.Invocation+"\x00"+a.Sources < b.Name+"\x00"+b.Invocation+"\x00"+b.Sources
		})
		selected[name] = map[string]bool{}
		for _, r := range resolved.Rules {
			if !moduleScope(r.Scope.Modules, name) || !conditionsMatch(profile, modules, name, r.When) {
				continue
			}
			if inherited(selected, name, r.ID) {
				continue
			}
			rv, err := renderRule(r)
			if err != nil {
				return nil, err
			}
			var applicable []string
			for _, target := range paths {
				if moduleScope(r.Scope.Modules, target) && conditionsMatch(profile, modules, target, r.When) {
					applicable = append(applicable, target)
				}
			}
			rv.Applicability = inlineList(applicable)
			v.Rules = append(v.Rules, rv)
			selected[name][r.ID] = true
		}
		for _, r := range resolved.Rules {
			if !selected[name][r.ID] {
				continue
			}
			for _, dependency := range r.Dependencies {
				if !selected[name][dependency.ID] && !inherited(selected, name, dependency.ID) {
					return nil, fmt.Errorf("rule dependency is not available in module scope: %s", r.ID)
				}
			}
		}
		if name == "." {
			for _, child := range paths {
				if child != "." {
					v.Children = append(v.Children, inline(path.Join(child, "AGENTS.md")))
				}
			}
			for _, unknown := range profile.UnknownItems {
				v.Unknown = append(v.Unknown, escape(unknown))
			}
			for _, warning := range resolved.Warnings {
				v.Warnings = append(v.Warnings, escape(warning))
			}
			sort.Strings(v.Unknown)
			sort.Strings(v.Warnings)
		}
		var out bytes.Buffer
		if err := document.Execute(&out, v); err != nil {
			return nil, errors.New("cannot render static instruction template")
		}
		files = append(files, File{Path: path.Join(name, "AGENTS.md"), Content: out.String()})
	}
	for _, rule := range resolved.Rules {
		delivered := false
		for _, ids := range selected {
			delivered = delivered || ids[rule.ID]
		}
		if !delivered {
			return nil, fmt.Errorf("selected rule cannot be represented in a detected module scope: %s", rule.ID)
		}
	}
	if err := budget(files); err != nil {
		return nil, err
	}
	return files, nil
}

func aggregate(input []model.Module) (map[string]*module, error) {
	result := map[string]*module{".": {path: "."}}
	caseNames := map[string]string{".": "."}
	for _, m := range input {
		if safeio.ValidatePath(m.Path) != nil || safeio.ValidatePath(m.Manifest) != nil || safeio.Sensitive(m.Path) || path.Dir(m.Manifest) != m.Path || strings.ContainsAny(m.Path, "`<>[]") || strings.Contains("/"+m.Path+"/", "/.ombp/") {
			return nil, errors.New("module has an unsafe path or mismatched manifest")
		}
		key := strings.ToLower(m.Path)
		if previous, exists := caseNames[key]; exists && previous != m.Path {
			return nil, errors.New("case-colliding module paths are unsupported")
		}
		caseNames[key] = m.Path
		if result[m.Path] == nil {
			if len(result) >= 256 {
				return nil, errors.New("rendered module count budget exceeded")
			}
			result[m.Path] = &module{path: m.Path}
		}
		x := result[m.Path]
		x.manifests = append(x.manifests, m.Manifest)
		x.languages = append(x.languages, m.Languages...)
	}
	for _, m := range result {
		m.manifests = sortedUnique(m.manifests)
		m.languages = sortedUnique(m.languages)
	}
	return result, nil
}

func renderCommand(c model.Command) (commandView, error) {
	if safeio.ValidatePath(c.Cwd) != nil || c.ExecutionStatus != "NOT_RUN" || len(c.Argv) == 0 || len(c.Argv) > 32 || (c.Status != "declared" && c.Status != "candidate" && c.Status != "unknown") {
		return commandView{}, errors.New("command declaration has unsafe path, state or arguments")
	}
	if len(c.Evidence) == 0 {
		return commandView{}, errors.New("command declaration requires evidence")
	}
	for _, evidence := range c.Evidence {
		if safeio.ValidatePath(evidence.Path) != nil || !hexDigest(evidence.SHA256) {
			return commandView{}, errors.New("command declaration has invalid evidence")
		}
	}
	if c.Status == "unknown" {
		return commandView{Name: escape(c.Name), Invocation: "unavailable; review declaration", Cwd: inline(c.Cwd), Status: inline(c.Status), Sources: sources(c.Evidence)}, nil
	}
	var args []string
	for _, arg := range c.Argv {
		if arg == "" || len(arg) > 256 || strings.IndexFunc(arg, unicode.IsControl) >= 0 || strings.ContainsAny(arg, "`$;&|<>\\()") || strings.HasPrefix(arg, "/") || (len(arg) > 1 && arg[1] == ':') {
			return commandView{}, errors.New("command invocation contains unsupported unsafe tokens")
		}
		if strings.ContainsAny(arg, " \t\"'") {
			arg = strconv.Quote(arg)
		}
		args = append(args, arg)
	}
	return commandView{Name: escape(c.Name), Invocation: inline(strings.Join(args, " ")), Cwd: inline(c.Cwd), Status: inline(c.Status), Sources: sources(c.Evidence)}, nil
}

func renderRule(r rules.Rule) (ruleView, error) {
	if r.ID == "" || !hexDigest(r.SHA256) || strings.Contains(r.Content, "<!-- ombp:") || !utf8.ValidString(r.Content) || strings.ContainsRune(r.Content, '\x00') {
		return ruleView{}, errors.New("resolved rule has invalid identity, digest or body")
	}
	conditions := []string{}
	for _, item := range []struct {
		name   string
		values []string
	}{{"languages", r.When.Languages}, {"frameworks", r.When.Frameworks}, {"databases", r.When.Databases}, {"project types", r.When.ProjectTypes}} {
		if len(item.values) > 0 {
			conditions = append(conditions, item.name+" "+inlineList(item.values))
		}
	}
	condition := "unconditional"
	if len(conditions) > 0 {
		condition = strings.Join(conditions, "; ")
	}
	source := inline(r.Source.Package)
	if r.Source.Path != "" {
		if safeio.ValidatePath(r.Source.Path) != nil {
			return ruleView{}, errors.New("rule source path is not relative")
		}
		source += " (" + inline(r.Source.Path) + ")"
	}
	return ruleView{
		ID: escape(r.ID), Title: escape(r.Title), Version: inline(r.Version), Severity: inline(r.Severity), Source: source,
		SHA256: inline(r.SHA256), Scope: "modules " + inlineList(r.Scope.Modules) + "; paths " + inlineList(r.Scope.Paths), Conditions: condition,
		Content: r.Content,
	}, nil
}

func conditionsMatch(profile model.Profile, modules map[string]*module, name string, conditions rules.Conditions) bool {
	for _, selector := range []struct {
		kind   string
		values []string
	}{{"language", conditions.Languages}, {"framework", conditions.Frameworks}, {"database", conditions.Databases}, {"project_type", conditions.ProjectTypes}} {
		if len(selector.values) == 0 || contains(selector.values, "*") {
			continue
		}
		found := false
		for _, fact := range profile.Facts {
			if fact.Kind != selector.kind || fact.Conflict || fact.Confidence <= 0 || (fact.Status != "declared" && fact.Status != "detected" && fact.Status != "confirmed") || (!contains(selector.values, fact.Name) && !contains(selector.values, fact.Value)) {
				continue
			}
			for _, evidence := range fact.Evidence {
				if owner(evidence.Path, modules) == name {
					found = true
				}
			}
		}
		if !found {
			return false
		}
	}
	return true
}

func owner(filename string, modules map[string]*module) string {
	result := "."
	for name := range modules {
		if name != "." && (strings.HasPrefix(filename, name+"/")) && len(name) > len(result) {
			result = name
		}
	}
	return result
}

func inherited(selected map[string]map[string]bool, name, id string) bool {
	if name == "." {
		return false
	}
	for parent := path.Dir(name); ; parent = path.Dir(parent) {
		if selected[parent][id] {
			return true
		}
		if parent == "." {
			return false
		}
	}
}

func moduleScope(patterns []string, name string) bool {
	for _, pattern := range patterns {
		if pattern == "*" || glob(pattern, name) {
			return true
		}
	}
	return false
}

func glob(pattern, name string) bool {
	p, n := strings.Split(pattern, "/"), strings.Split(name, "/")
	type state struct{ a, b int }
	cache := map[state]bool{}
	known := map[state]bool{}
	var match func(int, int) bool
	match = func(i, j int) bool {
		key := state{i, j}
		if known[key] {
			return cache[key]
		}
		known[key] = true
		value := false
		defer func() { cache[key] = value }()
		if i == len(p) {
			value = j == len(n)
		} else if p[i] == "**" {
			value = match(i+1, j) || j < len(n) && match(i, j+1)
		} else if j < len(n) {
			ok, _ := path.Match(p[i], n[j])
			value = ok && match(i+1, j+1)
		}
		return value
	}
	return match(0, 0)
}

func budget(files []File) error {
	for _, current := range files {
		total := 0
		for _, parent := range files {
			if parent.Path == "AGENTS.md" || current.Path == parent.Path || strings.HasPrefix(path.Dir(current.Path)+"/", path.Dir(parent.Path)+"/") {
				total += len(parent.Content)
			}
		}
		if total > adapters.CodexInstructionBudget {
			return errors.New("Codex cumulative instruction byte budget exceeded; no rules were truncated")
		}
	}
	return nil
}

func sources(evidence []model.Evidence) string {
	var values []string
	for _, e := range evidence {
		if safeio.ValidatePath(e.Path) == nil {
			value := e.Path
			if e.Pointer != "" {
				value += "#" + e.Pointer
			}
			values = append(values, inline(value))
		}
	}
	if len(values) == 0 {
		return "unavailable; review source"
	}
	return strings.Join(sortedUnique(values), ", ")
}

func escape(value string) string {
	var out strings.Builder
	for _, r := range value {
		if unicode.IsControl(r) {
			out.WriteString(" ")
		} else if strings.ContainsRune("\\`*_{}[]<>()!#|", r) {
			fmt.Fprintf(&out, "&#%d;", r)
		} else {
			out.WriteRune(r)
		}
	}
	return out.String()
}

func inline(value string) string {
	value = strings.Map(func(r rune) rune {
		if unicode.IsControl(r) {
			return ' '
		}
		return r
	}, value)
	longest, current := 0, 0
	for _, r := range value {
		if r == '`' {
			current++
			if current > longest {
				longest = current
			}
		} else {
			current = 0
		}
	}
	delimiter := strings.Repeat("`", longest+1)
	return delimiter + " " + value + " " + delimiter
}
func inlineList(values []string) string {
	values = sortedUnique(values)
	if len(values) == 0 {
		return "unknown"
	}
	for i := range values {
		values[i] = inline(values[i])
	}
	return strings.Join(values, ", ")
}
func contains(values []string, value string) bool {
	for _, v := range values {
		if v == value {
			return true
		}
	}
	return false
}
func sortedUnique(values []string) []string {
	values = append([]string{}, values...)
	sort.Strings(values)
	var out []string
	for _, value := range values {
		if len(out) == 0 || out[len(out)-1] != value {
			out = append(out, value)
		}
	}
	return out
}
func hexDigest(value string) bool {
	if len(value) != 64 {
		return false
	}
	for _, c := range value {
		if c < '0' || c > '9' {
			if c < 'a' || c > 'f' {
				return false
			}
		}
	}
	return true
}
